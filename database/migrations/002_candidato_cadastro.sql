-- Garante a estrutura exigida pelo POST /api/candidatos.
-- Aplicar no banco db_dogschool. Seguro para reexecução.
CREATE TABLE IF NOT EXISTS candidato (
    id_candidato INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    cpf CHAR(11) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    CONSTRAINT chk_candidato_cpf_formato CHECK (cpf ~ '^[0-9]{11}$')
);

